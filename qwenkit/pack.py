    ap.add_argument("--path", default=".", help="корень проекта (для --target project)")
    ap.add_argument("--only", choices=["commands", "agents"], help="установить только часть набора")
    ap.add_argument("--list", action="store_true", help="только показать состав набора")
    ap.add_argument("--overwrite", action="store_true", help="перезаписывать существующие файлы (делает .bak)")
    ap.add_argument("--dry-run", action="store_true", help="показать, что будет создано")
    args = ap.parse_args(argv)

    if args.list:
        print(f"\n{C_BOLD}Команды{C_RESET} (будут доступны как /имя):")
        for path in sorted(COMMANDS):
            name = "/" + path[:-3].replace("/", ":")
            desc = ""
            for line in COMMANDS[path].splitlines():
                if line.startswith("description:"):
                    desc = line.split(":", 1)[1].strip()
                    break
            print(f"  {C_GRN}{name:<18s}{C_RESET} {C_DIM}{desc}{C_RESET}")
        print(f"\n{C_BOLD}Субагенты{C_RESET} (доступны через /agents и автоделегирование):")
        for path in sorted(AGENTS):
            name = path[:-3]
            desc = ""
            for line in AGENTS[path].splitlines():
                if line.startswith("description:"):
                    desc = line.split(":", 1)[1].strip()
                    break
            print(f"  {C_GRN}{name:<18s}{C_RESET} {C_DIM}{desc[:88]}{C_RESET}")
        print()
        return 0

    if args.target == "user":
        base = Path.home() / ".qwen"
    else:
        base = Path(args.path).expanduser().resolve() / ".qwen"

    print(f"\n{C_BOLD}qwenkit pack{C_RESET} {C_DIM}→ {base}{C_RESET}")
    if args.dry_run:
        print(f"{C_YEL}--- DRY RUN ---{C_RESET}")

    created = skipped = 0
    if args.only in (None, "commands"):
        for rel, content in COMMANDS.items():
            st = _write(base / "commands" / rel, content, args.overwrite, args.dry_run)
            name = "/" + rel[:-3].replace("/", ":")
            if st == "skip":
                print(f"  {C_DIM}· {name:<18s} уже существует (--overwrite чтобы заменить){C_RESET}")
                skipped += 1
            else:
                mark, col = ("+", C_GRN) if st == "new" else ("~", C_YEL)
                print(f"  {col}{mark} {name:<18s}{C_RESET} {C_DIM}{base / 'commands' / rel}{C_RESET}")
                created += 1
    if args.only in (None, "agents"):
        for rel, content in AGENTS.items():
            st = _write(base / "agents" / rel, content, args.overwrite, args.dry_run)
            name = rel[:-3]
            if st == "skip":
                print(f"  {C_DIM}· agent {name:<13s} уже существует{C_RESET}")
                skipped += 1
            else:
                mark, col = ("+", C_GRN) if st == "new" else ("~", C_YEL)
                print(f"  {col}{mark} agent {name:<13s}{C_RESET} {C_DIM}{base / 'agents' / rel}{C_RESET}")
                created += 1

    print(f"\n  {C_GRN}создано: {created}{C_RESET}"
          + (f", {C_DIM}пропущено: {skipped}{C_RESET}" if skipped else ""))
    if not args.dry_run and created:
        print(f"\n{C_BOLD}Как пользоваться{C_RESET}")
        print(f"  {C_BOLD}qwen{C_RESET} → внутри наберите {C_BOLD}/{C_RESET} и увидите команды "
              f"(/git:commit, /review, /tests, …)")
        print(f"  Субагенты: {C_BOLD}/agents manage{C_RESET} — список и настройка; "
              f"обычно Qwen вызывает их сам по описанию.")
        print(f"  Явный вызов: «запусти агента reviewer на этом диффе».")
        print(f"  {C_DIM}Команды и агенты в ~/.qwen видны во всех проектах; "
              f"в <проект>/.qwen — только в нём и имеют приоритет.{C_RESET}")
    print()
    return 0
