def _write(dst: Path, content: str, overwrite: bool, dry: bool) -> str:
    """Записать файл. Возвращает 'new' | 'skip' | 'overwrite'."""
    existed = dst.exists()
    if existed and not overwrite:
        return "skip"
    if dry:
        return "overwrite" if existed else "new"
    dst.parent.mkdir(parents=True, exist_ok=True)
    if existed:
        bk = dst.with_suffix(dst.suffix + ".bak")
        shutil.copy2(dst, bk)
    dst.write_text(content.lstrip("\n"), encoding="utf-8")
    return "overwrite" if existed else "new"


